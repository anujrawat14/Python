import math

# Square root
print(math.sqrt(25))
# 5.0


# Power
print(math.pow(2, 3))
# 8.0


# Floor
print(math.floor(2.9))
# 2


# Ceiling
print(math.ceil(2.1))
# 3


# Truncate decimal part or give number closest to 0 
print(math.trunc(4.9))
# 4


# Factorial
print(math.factorial(5))
# 120
# 5 × 4 × 3 × 2 × 1


# Greatest Common Divisor
print(math.gcd(12, 8))
# 4


# Least Common Multiple
print(math.lcm(12, 8))
# 24

#pi constant
print(math.pi)
# 3.141592653589793

print(math.e)
# 2.718281828459045